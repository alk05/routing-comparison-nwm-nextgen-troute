import argparse
import itertools
import json
import os
from pathlib import Path
import matplotlib.cm as cm
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import xarray as xr


def load_datasets(forcing_dir, troute_dir, mapping_file, base_forecast_time):
    # Native NWM dataset
    base_path = Path(forcing_dir)
    nwm_streamflows = []
    for i in range(0, 18):
        current_valid_time = base_forecast_time + pd.Timedelta(hours=i)
        filename_prefix = current_valid_time.strftime("%Y%m%d%H%M")
        filepath = base_path / f"{filename_prefix}.CHRTOUT_DOMAIN1"

        if not filepath.exists():
            raise FileNotFoundError(f"Missing forcing file: {filepath}")

        with xr.open_dataset(filepath, engine="netcdf4") as ds:
            # Extract true valid time from internal NetCDF metadata
            if "model_output_valid_time" in ds.attrs:
                valid_time_str = ds.attrs["model_output_valid_time"].replace("_", " ")
                actual_valid_time = pd.to_datetime(valid_time_str, utc=True)
            else:
                actual_valid_time = pd.to_datetime(ds["time"].values[0], utc=True)

            streamflow_da = (
                ds["streamflow"]
                .expand_dims(time=[actual_valid_time])
                .load()
            )
            nwm_streamflows.append(streamflow_da)

    nwm_flow = xr.concat(nwm_streamflows, dim="time")

    # Converted T-Route (Parquet)
    folder_path = Path(troute_dir)
    parquet_file = None
    for filename in os.listdir(folder_path):
        if filename.startswith("converted_troute_output"):
            parquet_file = folder_path / filename
            break

    if parquet_file and parquet_file.exists():
        df_ro = pd.read_parquet(parquet_file)
        df_ro["time"] = pd.to_datetime(df_ro["time"], utc=True)
        df_ro = df_ro.set_index(["feature_id", "time"])
        ds_ro = df_ro.to_xarray()
        ro_flow = ds_ro["flow"]
    else:
        raise FileNotFoundError(
            f"No parquet file starting with 'converted_troute_output' found in {folder_path}"
        )

    # Crosswalk NWM and NextGen IDs
    with open(mapping_file, "r") as f:
        mapping_dict = json.load(f)
    convert_id = pd.Series(mapping_dict)

    # t_route_nhd (NetCDF)
    nc_file_path = None
    for filename_nc in os.listdir(folder_path):
        if filename_nc.startswith("troute_output") and filename_nc.endswith(
            (".nc", ".nc4", ".netcdf")
        ):
            nc_file_path = folder_path / filename_nc
            break

    if nc_file_path and nc_file_path.exists():
        with xr.open_dataset(nc_file_path, engine="netcdf4") as ds_t_route:
            troute_streamflow_da = ds_t_route["flow"].load()

        df_t_route = troute_streamflow_da.to_dataframe(
            name="value"
        ).reset_index()
        df_t_route = df_t_route.rename(
            columns={"feature_id": "location_id", "time": "value_time"}
        )
        df_t_route["variable_name"] = "streamflow"
        df_t_route["value_time"] = pd.to_datetime(
            df_t_route["value_time"], utc=True
        )
        df_t_route = df_t_route.set_index(["location_id", "value_time"])
    else:
        raise FileNotFoundError(
            f"No NetCDF file starting with 'troute_output' found in {folder_path}"
        )

    return nwm_flow, ro_flow, convert_id, df_t_route


def get_comparison_data(
    ngen_id,
    nwm_flow,
    ro_flow,
    convert_id,
    df_t_route,
    zero_threshold=0,
):

    lookup_id = f"nex-{ngen_id}" if not str(ngen_id).startswith("nex-") else str(ngen_id)
    ro_series = ro_flow.sel(feature_id=lookup_id).to_pandas()
   # ro_series = ro_flow.sel(feature_id=ngen_id_key).to_pandas()
   # ro_series = ro_flow.sel(feature_id=ngen_id).to_pandas()

    nwm_ids_raw = convert_id.get(f"nex-{str(ngen_id)}", [])
    filtered_nwm_data_dict = {}
    filtered_nwm_ids = []
    nwm_series_list = []

    troute_data_dict = {}
    troute_series_list = []

    nwm_mean_series = None
    if nwm_ids_raw:
        for ngen_id in nwm_ids_raw:
            nwm_individual_series = nwm_flow.sel(feature_id=ngen_id).to_pandas()
            if (
                not nwm_individual_series.empty
                and nwm_individual_series.max() > zero_threshold
            ):
                filtered_nwm_ids.append(ngen_id)
                filtered_nwm_data_dict[f"native_nwm_{int(ngen_id)}"] = (
                    nwm_individual_series
                )
                nwm_series_list.append(nwm_individual_series)

        if nwm_series_list:
            nwm_mean_series = pd.concat(
                nwm_series_list, axis=1, join="outer"
            ).mean(axis=1)

    if filtered_nwm_ids:
        for ngen_id in filtered_nwm_ids:
            troute_location_id = int(ngen_id)
            try:
                troute_streamflow_series = df_t_route.loc[
                    (troute_location_id, slice(None)), :
                ]
                troute_streamflow_series = troute_streamflow_series[
                    troute_streamflow_series["variable_name"] == "streamflow"
                ]["value"]
                if not troute_streamflow_series.empty:
                    troute_streamflow_series = (
                        troute_streamflow_series.reset_index(
                            level="location_id", drop=True
                        )
                    )
                    troute_streamflow_series.index = pd.to_datetime(
                        troute_streamflow_series.index
                    )
                    if not troute_streamflow_series.isnull().all():
                        troute_data_dict[f"t_route_{int(ngen_id)}"] = (
                            troute_streamflow_series
                        )
                        troute_series_list.append(troute_streamflow_series)
            except KeyError:
                pass

    troute_mean_series = None
    if troute_series_list:
        troute_mean_series = pd.concat(
            troute_series_list, axis=1, join="outer"
        ).mean(axis=1)

    return (
        ro_series,
        filtered_nwm_data_dict,
        nwm_mean_series,
        troute_data_dict,
        troute_mean_series,
    )


def plot_data(
    ngen_id,
    nwm_flow,
    ro_flow,
    convert_id,
    df_t_route,
    output_filename,
    zero_threshold=0,
):
    plt.figure(figsize=(12, 7))

    (
        ro_series,
        filtered_nwm_data_dict,
        nwm_mean_series,
        troute_data_dict,
        troute_mean_series,
    ) = get_comparison_data(
        ngen_id=ngen_id,
        nwm_flow=nwm_flow,
        ro_flow=ro_flow,
        convert_id=convert_id,
        df_t_route=df_t_route,
        zero_threshold=zero_threshold,
    )

    nwm_colors = plt.cm.YlOrRd([0.3, 0.5, 0.7, 0.9])
    troute_colors = plt.cm.GnBu([0.3, 0.5, 0.7, 0.9])

    nwm_color_cycle = itertools.cycle(nwm_colors)
    for nwm_label in sorted(filtered_nwm_data_dict.keys()):
        nwm_individual_series = filtered_nwm_data_dict[nwm_label]
        nwm_id = int(nwm_label.replace("native_nwm_", ""))
        plt.plot(
            nwm_individual_series.index,
            nwm_individual_series.values,
            label=f"Native NWM {nwm_id}",
            color=next(nwm_color_cycle),
            linestyle="--",
            alpha=0.7,
            linewidth=1,
        )

    if nwm_mean_series is not None:
        plt.plot(
            nwm_mean_series.index,
            nwm_mean_series.values,
            label="Native NWM Average",
            color="red",
            linewidth=4,
            linestyle="-",
        )

    troute_color_cycle = itertools.cycle(troute_colors)
    for troute_label in sorted(troute_data_dict.keys()):
        troute_individual_series = troute_data_dict[troute_label]
        troute_nwm_id = int(troute_label.replace("t_route_", ""))
        plt.plot(
            troute_individual_series.index,
            troute_individual_series.values,
            label=f"T-Route NHD {troute_nwm_id}",
            color=next(troute_color_cycle),
            linestyle="-",
            alpha=0.7,
            linewidth=1,
        )

    if troute_mean_series is not None:
        plt.plot(
            troute_mean_series.index,
            troute_mean_series.values,
            label="T-Route NHD Average",
            color="darkblue",
            linewidth=5,
            linestyle="--",
        )

    plt.plot(
        ro_series.index,
        ro_series.values,
        label=f"Converted T-Route {ngen_id}",
        color="black",
        linewidth=4,
    )

    plt.title(f"Flow Comparison for nex-{ngen_id}")
    plt.xlabel("Time")
    plt.ylabel("Flow Rate (m^3/s)")
    plt.legend(bbox_to_anchor=(1.05, 1), loc="upper left")
    plt.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig(output_filename, format="png")
    plt.close()
    print(f"Saved plot: {output_filename}")


def main():
    env_start_time = os.getenv("START_TIME")

    parser = argparse.ArgumentParser(
        description="Process flow comparisons and mapping."
    )

    parser.add_argument("ids", type=int, nargs="+", help="NextGen IDs to plot")
    parser.add_argument(
        "--nwm-to-ngen-map",
        type=str,
        required=True,
        help="Path to NWM to NextGen mapping JSON/file",
    )
    parser.add_argument(
        "--channel-forcing-dir",
        type=str,
        required=True,
        help="Directory containing channel forcing files",
    )
    parser.add_argument(
        "--troute-output-dir",
        type=str,
        required=True,
        help="Directory containing t-route output files",
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default="./plots",
        help="Directory to save generated plots",
    )
    parser.add_argument(
        "--start-time",
        type=str,
        default=env_start_time,
        required=(env_start_time is None),
        help="Forecast start time (e.g. 202604300000)",
    )
    parser.add_argument(
        "--output-prefix",
        type=str,
        default="flow_comparison",
        help="Prefix for saved PNGs",
    )

    args = parser.parse_args()

    map_file = Path(args.nwm_to_ngen_map).expanduser()
    forcing_dir = Path(args.channel_forcing_dir).expanduser()
    troute_dir = Path(args.troute_output_dir).expanduser()

    out_dir = Path(args.output_dir).expanduser()
    out_dir.mkdir(parents=True, exist_ok=True)

    base_forecast_time = pd.to_datetime(args.start_time, utc=True)

    # Load datasets ONCE
    nwm_flow, ro_flow, convert_id, df_t_route = load_datasets(
    forcing_dir=forcing_dir,
    troute_dir=troute_dir,
    mapping_file=map_file,
    base_forecast_time=base_forecast_time,
    )

    # Iterate through each requested ID
    for ngen_id in args.ids:
        filename = out_dir / f"{args.output_prefix}_{ngen_id}.png"
        plot_data(
            ngen_id=ngen_id,
            nwm_flow=nwm_flow,
            ro_flow=ro_flow,
            convert_id=convert_id,
            df_t_route=df_t_route,
            output_filename=filename,
        )


if __name__ == "__main__":
    main()
